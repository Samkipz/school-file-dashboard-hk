// Reproduce the custom SQL from the authoritative baseline snapshot and reviewed trigger source.
import { readFileSync, writeFileSync } from 'node:fs'
const snapshot = JSON.parse(readFileSync('drizzle/meta/0000_snapshot.json', 'utf8'))
const quote = value => `"${value.replaceAll('"', '""')}"`
const statements = []
const statuses = {
  schools: ['active','suspended','archived'], school_memberships: ['invited','active','suspended','left'], staff_profiles: ['active','inactive'], learners: ['active','left','completed','archived'], learner_admissions: ['active','closed'], academic_years: ['draft','active','closed'], class_groups: ['active','closed'], learner_enrolments: ['active','withdrawn','completed'], subject_catalogue: ['active','retired'], subject_offerings: ['active','closed'], learner_subject_enrolments: ['active','withdrawn','completed'], teacher_assignments: ['active','ended','revoked'],
}
for (const table of Object.values(snapshot.tables)) {
  const name = quote(table.name)
  if (table.columns.row_version) statements.push(`ALTER TABLE ${name} ADD CONSTRAINT ${quote(table.name + '_version_positive')} CHECK (row_version > 0);`)
  if (statuses[table.name]) statements.push(`ALTER TABLE ${name} ADD CONSTRAINT ${quote(table.name + '_status_valid')} CHECK (status IN (${statuses[table.name].map(s => `'${s}'`).join(', ')}));`)
  for (const col of Object.values(table.columns)) {
    if (col.type === 'varchar(160)' && col.notNull) statements.push(`ALTER TABLE ${name} ADD CONSTRAINT ${quote(table.name + '_' + col.name + '_nonblank')} CHECK (length(trim(${quote(col.name)})) > 0);`)
  }
  const indexes = [Object.values(table.columns).filter(c => c.primaryKey).map(c => c.name), ...Object.values(table.uniqueConstraints).map(u => u.columns), ...Object.values(table.indexes).filter(i => !i.where).map(i => i.columns.map(c => c.expression))]
  let n = 0
  for (const fk of Object.values(table.foreignKeys)) {
    const cols = fk.columnsFrom
    if (indexes.some(i => cols.every((c, j) => i[j] === c))) continue
    statements.push(`CREATE INDEX ${quote(table.name + '_fk_' + (++n) + '_idx')} ON ${name} (${cols.map(quote).join(', ')});`)
    indexes.push(cols)
  }
}
statements.push('CREATE INDEX session_expires_idx ON session ("expiresAt");', 'CREATE INDEX verification_identifier_idx ON verification (identifier);', 'CREATE INDEX verification_expires_idx ON verification ("expiresAt");')
statements.push(readFileSync('scripts/foundation-triggers.sql', 'utf8'))
writeFileSync('drizzle/0001_foundation_guards.sql', '-- Generated by scripts/generate-foundation-guards.mjs; triggers are reviewed SQL.\n' + statements.join('\n--> statement-breakpoint\n'))
